-- PVE-BMS SALES AND INVOICE DATABASE
-- PostgreSQL 18
-- Designed for existing PVE-BMS database

BEGIN;

-- 1. CUSTOMERS
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    address VARCHAR(255),
    credit_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    credit_approved_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_customer_name_phone UNIQUE (name, phone)
);

-- 2. SALES / INVOICE
CREATE TABLE IF NOT EXISTS sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no VARCHAR(50) NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES customers(id),
    customer_name_snapshot VARCHAR(150),
    customer_phone_snapshot VARCHAR(20),
    sold_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    subtotal NUMERIC(14,2) NOT NULL DEFAULT 0,
    discount_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    grand_total NUMERIC(14,2) NOT NULL DEFAULT 0,
    credit_due_date DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_sales_status
        CHECK (status IN ('DRAFT', 'COMPLETED', 'VOIDED')),

    CONSTRAINT chk_sales_totals
        CHECK (
            subtotal >= 0
            AND discount_total >= 0
            AND grand_total >= 0
        )
);

-- 3. SALE ITEMS
CREATE TABLE IF NOT EXISTS sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    cost_price NUMERIC(12,2) NOT NULL,
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0,

    line_total NUMERIC(14,2)
        GENERATED ALWAYS AS (
            ROUND(quantity * unit_price - discount_amount, 2)
        ) STORED,

    CONSTRAINT chk_sale_item_values
        CHECK (
            quantity > 0
            AND unit_price >= 0
            AND cost_price >= 0
            AND discount_amount >= 0
            AND discount_amount <= quantity * unit_price
        )
);

-- 4. PAYMENTS
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT REFERENCES sales(id),
    customer_id BIGINT REFERENCES customers(id),
    amount NUMERIC(14,2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    reference_no VARCHAR(100),
    paid_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_payment_amount CHECK (amount > 0),

    CONSTRAINT chk_payment_method
        CHECK (
            payment_method IN (
                'CASH',
                'CARD',
                'BANK_TRANSFER'
            )
        ),

    CONSTRAINT chk_payment_reference
        CHECK (sale_id IS NOT NULL OR customer_id IS NOT NULL)
);

-- 5. CUSTOMER CREDIT LEDGER
CREATE TABLE IF NOT EXISTS credit_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    sale_id BIGINT REFERENCES sales(id),
    payment_id BIGINT REFERENCES payments(id),
    transaction_type VARCHAR(20) NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_credit_type
        CHECK (
            transaction_type IN (
                'DEBIT',
                'CREDIT',
                'ADJUSTMENT'
            )
        ),

    CONSTRAINT chk_credit_amount
        CHECK (
            amount > 0
        )
);

-- 6. INVENTORY MOVEMENTS
CREATE TABLE IF NOT EXISTS inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    rack_inventory_id BIGINT REFERENCES rack_inventory(id),
    sale_id BIGINT REFERENCES sales(id),
    sale_item_id BIGINT REFERENCES sale_items(id),
    quantity_change INTEGER NOT NULL,
    movement_type VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_inventory_movement_type
        CHECK (
            movement_type IN (
                'SALE',
                'SALE_REVERSAL',
                'ADJUSTMENT'
            )
        ),

    CONSTRAINT chk_inventory_quantity
        CHECK (quantity_change <> 0)
);

-- INDEXES
CREATE INDEX IF NOT EXISTS idx_sales_customer
    ON sales(customer_id);

CREATE INDEX IF NOT EXISTS idx_sales_sold_at
    ON sales(sold_at);

CREATE INDEX IF NOT EXISTS idx_sale_items_sale
    ON sale_items(sale_id);

CREATE INDEX IF NOT EXISTS idx_sale_items_product
    ON sale_items(product_id);

CREATE INDEX IF NOT EXISTS idx_payments_sale
    ON payments(sale_id);

CREATE INDEX IF NOT EXISTS idx_payments_customer
    ON payments(customer_id);

CREATE INDEX IF NOT EXISTS idx_credit_customer
    ON credit_transactions(customer_id);

CREATE INDEX IF NOT EXISTS idx_inventory_movements_product
    ON inventory_movements(product_id);

CREATE INDEX IF NOT EXISTS idx_inventory_movements_sale
    ON inventory_movements(sale_id);

COMMIT;
